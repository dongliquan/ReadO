// ===== Editor themes: Atom One Light / One Dark =====
// Shared by the main page (source.html) and the diff windows (diffwin.html).
function defineReadoThemes(monaco) {
  monaco.editor.defineTheme('one-light', {
    base: 'vs',
    inherit: true,
    rules: [
      { token: '', foreground: '383a42', background: 'fafafa' },
      { token: 'comment', foreground: 'a0a1a7', fontStyle: 'italic' },
      { token: 'keyword', foreground: 'a626a4' },
      { token: 'string', foreground: '50a14f' },
      { token: 'number', foreground: '986801' },
      { token: 'type', foreground: 'c18401' },
      { token: 'type.identifier', foreground: 'c18401' },
      { token: 'identifier', foreground: '383a42' },
      { token: 'delimiter', foreground: '383a42' },
      { token: 'tag', foreground: 'e45649' },
      { token: 'attribute.name', foreground: 'b76b01' },
      { token: 'attribute.value', foreground: '50a14f' },
    ],
    colors: {
      'editor.background': '#fafafa',
      'editor.foreground': '#383a42',
      'editor.lineHighlightBackground': '#f0f0f1',
      'editorLineNumber.foreground': '#a0a1a7',
      'editorLineNumber.activeForeground': '#383a42',
      'editorCursor.foreground': '#526fff',
      'editor.selectionBackground': '#e5e5e6',
      'editor.inactiveSelectionBackground': '#f0f0f1',
    },
  });
  // One Dark, kept readable (scripts/contrast_check.py: text 4.5:1 on #282c34, no
  // pure red / green / magenta). Monaco's built-in vs / vs-dark rules for a
  // language (string.sql #ff0000, predefined.sql #ff00ff, string.yaml #0451a5 …)
  // are more specific than 'string' and would win, so One Dark names them too.
  const red = 'ef8a91', green = '98c379', orange = 'd19a66', yellow = 'e5c07b', blue = '61afef',
    cyan = '56b6c2', purple = 'c678dd', text = 'abb2bf', mute = '8f96a2';
  monaco.editor.defineTheme('one-dark', {
    base: 'vs-dark',
    inherit: true,
    rules: [
      { token: '', foreground: text, background: '282c34' },
      { token: 'comment', foreground: mute, fontStyle: 'italic' },
      { token: 'keyword', foreground: purple },
      { token: 'string', foreground: green },
      { token: 'number', foreground: orange },
      { token: 'type', foreground: yellow },
      { token: 'type.identifier', foreground: yellow },
      { token: 'identifier', foreground: text },
      { token: 'delimiter', foreground: text },
      { token: 'tag', foreground: red },
      { token: 'attribute.name', foreground: orange },
      { token: 'attribute.value', foreground: green },
      // what the built-in themes would otherwise paint
      { token: 'string.sql', foreground: green },
      { token: 'string.html', foreground: green },
      { token: 'string.yaml', foreground: green },
      { token: 'predefined.sql', foreground: blue },
      { token: 'operator.sql', foreground: cyan },
      { token: 'operator.scss', foreground: cyan },
      { token: 'operator.swift', foreground: cyan },
      { token: 'regexp', foreground: cyan },
      { token: 'annotation', foreground: yellow },
      { token: 'invalid', foreground: red },
      { token: 'metatag', foreground: red },
      { token: 'variable.predefined', foreground: red },
      { token: 'delimiter.html', foreground: text },
      { token: 'delimiter.xml', foreground: text },
      { token: 'attribute.value.html', foreground: green },
      { token: 'attribute.value.xml', foreground: green },
      { token: 'attribute.value.number', foreground: orange },
      { token: 'attribute.value.unit', foreground: orange },
      { token: 'tag.id.pug', foreground: orange },
      { token: 'tag.class.pug', foreground: orange },
    ],
    colors: {
      'editor.background': '#282c34',
      'editor.foreground': '#abb2bf',
      'editor.lineHighlightBackground': '#2c313a',
      'editorLineNumber.foreground': '#8f96a2',
      'editorLineNumber.activeForeground': '#d7dae0',
      'editorCursor.foreground': '#528bff',
      'editor.selectionBackground': '#3e4451',
      'editor.inactiveSelectionBackground': '#363c46',
      'editor.findMatchHighlightBackground': '#d19a6640',
      'editorBracketHighlight.foreground1': '#d19a66',
      'editorBracketHighlight.foreground2': '#c678dd',
      'editorBracketHighlight.foreground3': '#61afef',
      'editorBracketHighlight.unexpectedBracket.foreground': '#ef8a91',
      'editorError.foreground': '#ef8a91',
      'editorWarning.foreground': '#e5c07b',
      'editorInfo.foreground': '#61afef',
      // diff: a faint tint for the line, a little more for the characters that changed
      'diffEditor.removedLineBackground': '#e06c7512',
      'diffEditor.removedTextBackground': '#e06c7524',
      'diffEditor.insertedLineBackground': '#98c3790f',
      'diffEditor.insertedTextBackground': '#98c3791f',
      'diffEditorGutter.removedLineBackground': '#e06c7526',
      'diffEditorGutter.insertedLineBackground': '#98c37921',
      'diffEditorOverview.removedForeground': '#e06c7599',
      'diffEditorOverview.insertedForeground': '#98c37999',
    },
  });
}
